#!/usr/bin/env bash
# gate-receipt.sh — incremental gate receipts (bd-sbf).
#
# A gate is a make target that ends in a verdict: `make test`, `make
# demos-dl-parity`, `make capture-corpus-check`.  Running one costs seconds to
# minutes, and most runs re-decide a question whose inputs did not change since
# the last green answer.  A *receipt* records one green run against a digest of
# its declared inputs; a later run with the same digest restores the log and
# the verdict without executing anything.
#
# INVARIANTS (breaking one is worse than being slow)
#   1. A false hit is worse than a slow miss.  The digest errs WIDE: when in
#      doubt include the file, include the repo, include the environment.
#   2. Only exit 0 is receipted.  A red gate always re-runs, so a receipt can
#      never turn a red gate green.
#   3. The inspection surface survives.  A hit restores the recorded
#      <target>-LATEST.txt byte-for-byte and prints where it is (AGENTS.md:
#      inspect the log, never re-run to look).
#   4. The receipt records the TARGET's exit code, not an inner command's.
#      This is by construction: `run` wraps the whole `*-uncached` target.
#   5. The cache is machine-local derived state, never committed.
#
# THE SHAPE IN cl-project.mk
#   test:            @$(GATE_RECEIPT) run test --log <out> -- $(MAKE) --no-print-directory test-uncached
#   test-uncached:   <the recipe exactly as it was before>
# On a miss the target behaves exactly as it did before receipts existed (same
# capture-output, same LATEST log, same verdict), so adopting receipts cannot
# move a verdict through a changed recipe.
#
# USAGE
#   gate-receipt run    GATE --log PATH [opts] -- CMD...
#   gate-receipt digest GATE [opts] [--verbose]
#   gate-receipt status [--cache DIR] [--verbose]
#   gate-receipt clean  [--cache DIR] [--all | GATE...]
#   gate-receipt selftest
#
#   opts: --root DIR            project root (default: .)
#         --cache DIR           receipt store (default: ROOT/.gate-cache)
#         --input PATH          file or dir, relative to ROOT (repeatable)
#         --exclude GLOB        extra basename glob to skip (repeatable)
#         --siblings DIR        walk sibling repos (dirs holding an *.asd)
#         --no-siblings         do not walk them
#         --stamp NAME=VALUE    extra digest input (repeatable)
#         --stamp-env NAME      digest input read from the environment
#         --sbcl PATH           stamp PATH and its --version
#         --cache-version N     bump to invalidate every receipt
#         --verbose             digest: print the manifest
#
#   env: FORCE=1  behave as a miss even on an identical digest.
#
# WHAT IS EXCLUDED, AND WHY (do not "simplify" these away)
#   build-info.sexp   regenerated by every make run; including it means no
#                     receipt ever hits (the trap that silently disables this)
#   *.fasl, .git      derived
#   work/ tmp/        run outputs; gitignored in every adopting repo
#   .gate-cache/      the receipts themselves (otherwise: never hits again)
# A project whose source lives in a directory with one of those names overrides
# with GATE_EXCLUDES in its Makefile; do not widen the defaults for everyone.
#
# SIBLING REPOS ARE INPUTS.  cl-project.mk initialises ASDF with
# (:tree PARENT_DIR), so a test can load a changed sibling checkout.  A sibling
# change that is not in the digest is a silent false hit.  Siblings are walked
# with an allow-list of file types (Lisp source and the data a Lisp program
# reads) because a full walk of this repos/ tree is ~38 GB of build output.

set -uo pipefail

PROG=gate-receipt
CACHE_VERSION_DEFAULT=1

# Basename globs pruned from every walk.
DEFAULT_EXCLUDES=(
  .git .gate-cache
  '*.fasl' '*.dfsl' '*.fas' '*.lib' '*.x86f' '*.amd64f' '*.lx64fsl'
  build-info.sexp
  work tmp .dart_tool node_modules .cache .pytest_cache
  '*.db' '*.db-journal' '*.db-wal' '*.db-shm'
)

# What a sibling repo contributes.  Lisp source plus the data files a Lisp
# program reads (fonts, icon tables, JSON theme tokens).  A binary asset that
# is NOT here is still covered when the root project owns it: the root is
# walked in full.
SIBLING_EXTS=(
  '*.lisp' '*.asd' '*.asdf' '*.cl' '*.sexp' '*.lsp'
  '*.json' '*.edn' '*.csv' '*.ttf' '*.otf' '*.ttc' '*.png' '*.svg' '*.jpg'
  '*.dart' '*.yaml' '*.yml'
)

TMPFILES=()
SCRATCH=
die() { printf '%s: %s\n' "$PROG" "$*" >&2; exit 2; }
say() { printf '%s: %s\n' "$PROG" "$*"; }

cleanup() {
  local f
  for f in "${TMPFILES[@]+"${TMPFILES[@]}"}"; do rm -f -- "$f"; done
  if [ -n "$SCRATCH" ] && [ -d "$SCRATCH" ]; then rm -rf -- "$SCRATCH"; fi
}
trap cleanup EXIT

tmpfile() {
  local f
  f=$(mktemp "${TMPDIR:-/tmp}/gate-receipt-$1.XXXXXX") || die "mktemp failed"
  TMPFILES+=("$f")
  printf '%s' "$f"
}

now_ms() { date +%s%3N; }
short8() { printf '%.8s' "$1"; }

usage() { sed -n '2,80p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

# ── digest ────────────────────────────────────────────────────────────────
GATE=
ROOT=$PWD
CACHE=
LOG=
CACHE_VERSION=$CACHE_VERSION_DEFAULT
VERBOSE=0
SIBLINGS=
WALK_SIBLINGS=1
SBCL_BIN=
INPUTS=()
EXCLUDES=()
STAMPS=()
STAMP_ENVS=()
MISSING=()
MANIFEST=
DIGEST=
CMDSTR=

# parse_opts <args...> — consumes recognised options; sets OPT_LEFT to the
# first argument it did not consume (the caller decides what that means).
parse_opts() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --root)          ROOT=${2:-}; [ -n "$ROOT" ] || die "--root needs a value"; shift 2 ;;
      --cache)         CACHE=${2:-}; [ -n "$CACHE" ] || die "--cache needs a value"; shift 2 ;;
      --log)           LOG=${2:-}; [ -n "$LOG" ] || die "--log needs a value"; shift 2 ;;
      --input)         INPUTS+=("${2:-}"); shift 2 ;;
      --exclude)       EXCLUDES+=("${2:-}"); shift 2 ;;
      --stamp)         STAMPS+=("${2:-}"); shift 2 ;;
      --stamp-env)     STAMP_ENVS+=("${2:-}"); shift 2 ;;
      --siblings)      SIBLINGS=${2:-}; [ -n "$SIBLINGS" ] || die "--siblings needs a value"; shift 2 ;;
      --no-siblings)   WALK_SIBLINGS=0; shift ;;
      --sbcl)          SBCL_BIN=${2:-}; [ -n "$SBCL_BIN" ] || die "--sbcl needs a value"; shift 2 ;;
      --cache-version) CACHE_VERSION=${2:-}; [ -n "$CACHE_VERSION" ] || die "--cache-version needs a value"; shift 2 ;;
      --verbose|-v)    VERBOSE=1; shift ;;
      *)               return 1 ;;
    esac
  done
  return 0
}

abs_under_root() {
  case "$1" in
    /*) printf '%s' "$1" ;;
    *)  printf '%s/%s' "$ROOT" "$1" ;;
  esac
}

# find(1) prefix that prunes the exclusion globs at any depth.
prune_args() {
  local first=1 g
  PRUNE=( \( )
  for g in "${DEFAULT_EXCLUDES[@]}" "${EXCLUDES[@]+"${EXCLUDES[@]}"}"; do
    [ "$first" -eq 1 ] || PRUNE+=( -o )
    PRUNE+=( -name "$g" )
    first=0
  done
  PRUNE+=( \) -prune -o )
}

sibling_ext_args() {
  local first=1 e
  EXT_ARGS=( \( )
  for e in "${SIBLING_EXTS[@]}"; do
    [ "$first" -eq 1 ] || EXT_ARGS+=( -o )
    EXT_ARGS+=( -name "$e" )
    first=0
  done
  EXT_ARGS+=( \) )
}

# build_manifest — writes the manifest to $MANIFEST and sets $DIGEST.
build_manifest() {
  local list hashes nfiles nhashes abs p m s v dist
  list=$(tmpfile files)
  hashes=$(tmpfile hash)

  prune_args
  sibling_ext_args

  : >"$list"
  MISSING=()
  for p in "${INPUTS[@]+"${INPUTS[@]}"}"; do
    abs=$(abs_under_root "$p")
    if [ -f "$abs" ]; then
      printf '%s\0' "$abs" >>"$list"
    elif [ -d "$abs" ]; then
      find "$abs" "${PRUNE[@]}" -type f -print0 >>"$list"
    else
      # A declared input that does not exist yet: record it, so creating it
      # later changes the digest instead of being invisible.
      MISSING+=("$p")
    fi
  done

  if [ "$WALK_SIBLINGS" -eq 1 ] && [ -n "$SIBLINGS" ] && [ -d "$SIBLINGS" ]; then
    local sib
    for sib in "$SIBLINGS"/*; do
      [ -d "$sib" ] || continue
      [ "$sib" -ef "$ROOT" ] && continue
      compgen -G "$sib/*.asd" >/dev/null || continue
      find "$sib" "${PRUNE[@]}" -type f "${EXT_ARGS[@]}" -print0 >>"$list"
    done
  fi

  LC_ALL=C sort -zu -o "$list" "$list"
  nfiles=$(tr -dc '\0' <"$list" | wc -c)
  # One sha256sum process per batch, input order preserved; the file list is
  # already sorted, so the records come out sorted by path.
  xargs -0 -r sha256sum --zero <"$list" >"$hashes" 2>/dev/null
  nhashes=$(tr -dc '\0' <"$hashes" | wc -c)

  MANIFEST=$(tmpfile manifest)
  {
    printf 'cache_version=%s\n' "$CACHE_VERSION"
    printf 'gate=%s\n' "$GATE"
    printf 'cmd=%s\n' "$CMDSTR"
    tr '\0' '\n' <"$hashes" | awk '{ print "file " substr($1,1,64) " " substr($0,67) }'
    for m in "${MISSING[@]+"${MISSING[@]}"}"; do printf 'missing %s\n' "$m"; done
    {
      for s in "${STAMPS[@]+"${STAMPS[@]}"}"; do printf '%s\n' "$s"; done
      for v in "${STAMP_ENVS[@]+"${STAMP_ENVS[@]}"}"; do printf '%s=%s\n' "$v" "${!v-}"; done
      if [ -n "$SBCL_BIN" ]; then
        printf 'sbcl=%s\n' "$SBCL_BIN"
        printf 'sbcl_version=%s\n' "$("$SBCL_BIN" --version 2>&1 | head -1)"
      fi
      dist=$HOME/quicklisp/dists/quicklisp/distinfo.txt
      if [ -f "$dist" ]; then
        printf 'ql_dist=%s\n' "$(sha256sum "$dist" | cut -c1-16)"
      fi
      printf 'asdf_source_registry=%s\n' "${ASDF_SOURCE_REGISTRY-}"
      printf 'sbcl_home=%s\n' "${SBCL_HOME-}"
    } | LC_ALL=C sort | sed 's/^/stamp /'
    if [ "$nfiles" -ne "$nhashes" ]; then
      # A file vanished mid-walk (concurrent build).  Never let that read as a
      # stable tree: this line forces a miss.
      printf 'unstable=%s-%s\n' "$(date +%s%N)" "$RANDOM"
    fi
  } >"$MANIFEST"

  DIGEST=$(sha256sum "$MANIFEST" | cut -c1-64)
}

# ── run ───────────────────────────────────────────────────────────────────
run_gate() {
  GATE=${1:-}
  [ -n "$GATE" ] || die "run needs a gate name"
  shift
  local -a cmd=()
  local seen_dd=0
  while [ $# -gt 0 ]; do
    if [ "$seen_dd" -eq 1 ]; then cmd+=("$1"); shift; continue; fi
    case "$1" in
      --) seen_dd=1; shift ;;
      --root|--cache|--log|--input|--exclude|--stamp|--stamp-env|--siblings|--sbcl|--cache-version)
        [ $# -ge 2 ] || die "$1 needs a value"
        parse_opts "$1" "$2" || die "bad option $1"
        shift 2 ;;
      --no-siblings|--verbose|-v)
        parse_opts "$1" || die "bad option $1"
        shift ;;
      *) die "unknown option '$1' (put the command after --)" ;;
    esac
  done
  [ "$seen_dd" -eq 1 ] || die "run needs '--' before the command"
  [ ${#cmd[@]} -gt 0 ] || die "run needs a command after '--'"

  ROOT=$(cd "$ROOT" && pwd) || die "no such root"
  [ -n "$CACHE" ] || CACHE=$ROOT/.gate-cache
  [ -n "$LOG" ] || die "run needs --log PATH (the file a hit must restore)"
  CMDSTR="${cmd[*]}"

  build_manifest
  local dir=$CACHE/$GATE/$DIGEST
  local d8; d8=$(short8 "$DIGEST")

  if [ -f "$dir/code" ] && [ -z "${FORCE-}" ]; then
    local code; code=$(cat "$dir/code")
    if [ "$code" = 0 ]; then
      if [ -f "$dir/log" ]; then
        cp -f "$dir/log" "$LOG"
        printf '%s: cached (%ss, %s) — log: %s\n' \
          "$GATE" "$(cat "$dir/elapsed" 2>/dev/null || echo '?')" "$d8" "$LOG"
        local v
        v=$(grep -E '^=== VERDICT:|^Passed:|^Failed:' "$LOG" 2>/dev/null | tail -1)
        [ -n "$v" ] && printf '  %s\n' "$v"
        exit 0
      elif [ "$(cat "$dir/log_state" 2>/dev/null)" = none ]; then
        rm -f "$LOG"
        printf '%s: cached (%ss, %s) — no log for this gate\n' \
          "$GATE" "$(cat "$dir/elapsed" 2>/dev/null || echo '?')" "$d8"
        exit 0
      else
        # A receipt whose log is gone cannot honour invariant 3: re-run.
        say "$GATE: receipt $d8 lost its log — re-running"
      fi
    else
      # Should never exist (only green is receipted); if it does, ignore it.
      say "$GATE: discarding non-green receipt $d8"
      rm -rf -- "$dir"
    fi
  elif [ -f "$dir/code" ]; then
    say "$GATE: FORCE set — re-running despite receipt $d8"
  fi

  local t0 t1 rc elapsed secs tmp
  t0=$(now_ms)
  "${cmd[@]}"
  rc=$?
  t1=$(now_ms)
  elapsed=$((t1 - t0))
  secs=$(printf '%d.%d' "$((elapsed / 1000))" "$((elapsed % 1000 / 100))")

  if [ "$rc" -ne 0 ]; then
    # Invariant 2: nothing is written for a red gate.
    exit "$rc"
  fi

  mkdir -p "$CACHE/$GATE" 2>/dev/null || { say "$GATE: cache not writable — not recorded"; exit 0; }
  tmp=$(mktemp -d "$CACHE/$GATE/.tmp.XXXXXX") || { say "$GATE: mktemp failed — not recorded"; exit 0; }
  printf '%s\n' "$rc" >"$tmp/code"
  printf '%s\n' "$elapsed" >"$tmp/elapsed_ms"
  printf '%s\n' "$secs" >"$tmp/elapsed"
  printf '%s\n' "$(date -Iseconds)" >"$tmp/recorded"
  printf '%s\n' "$CMDSTR" >"$tmp/cmd"
  cp -f "$MANIFEST" "$tmp/manifest"
  if [ -f "$LOG" ]; then
    cp -f "$LOG" "$tmp/log"
    printf 'file\n' >"$tmp/log_state"
    printf '%s\n' "$LOG" >"$tmp/log_path"
  else
    printf 'none\n' >"$tmp/log_state"
  fi
  rm -rf -- "$dir"
  mv -T "$tmp" "$dir" || { say "$GATE: could not install receipt"; exit 0; }
  printf '%s\n' "$DIGEST" >"$CACHE/$GATE/LATEST"
  printf '%s: receipt %s written (green, %ss) — log: %s\n' "$GATE" "$d8" "$secs" "$LOG"
  exit 0
}

# ── digest (diagnostic) ───────────────────────────────────────────────────
digest_gate() {
  GATE=${1:-}
  [ -n "$GATE" ] || die "digest needs a gate name"
  shift
  parse_opts "$@" || die "bad option"
  ROOT=$(cd "$ROOT" && pwd) || die "no such root: $ROOT"
  [ ${#INPUTS[@]} -gt 0 ] || die "digest needs at least one --input"
  build_manifest
  printf '%s\n' "$DIGEST"
  if [ "$VERBOSE" -eq 1 ]; then
    printf '%s\n' '--- manifest ---'
    cat "$MANIFEST"
  fi
  exit 0
}

# ── status / clean ────────────────────────────────────────────────────────
status_cache() {
  local cache=$1
  [ -d "$cache" ] || { say "no receipts at $cache"; return 0; }
  local g
  printf '%-22s %-10s %-20s %8s %s\n' GATE DIGEST RECORDED ELAPSED LOG
  for g in "$cache"/*; do
    [ -d "$g" ] || continue
    [ -f "$g/LATEST" ] || continue
    local name d dir rec elapsed logp n
    name=$(basename "$g")
    d=$(cat "$g/LATEST")
    dir=$g/$d
    rec=$(cat "$dir/recorded" 2>/dev/null || echo '?')
    elapsed=$(cat "$dir/elapsed" 2>/dev/null || echo '?')
    logp=$(cat "$dir/log_path" 2>/dev/null || echo '(none)')
    n=$(find "$g" -mindepth 1 -maxdepth 1 -type d ! -name '.tmp*' | wc -l)
    printf '%-22s %-10s %-20s %8s %s\n' "$name" "$(short8 "$d")" "$rec" "$elapsed" "$logp"
    if [ "$VERBOSE" -eq 1 ]; then
      printf '  receipts: %s  manifest: %s\n' "$n" "$dir/manifest"
    fi
  done
}

clean_cache() {
  local cache=$1; shift
  case "$cache" in
    ''|'/'|'/tmp'|'/home'|'/usr'|'/var'|'/etc'|"$HOME"|"$HOME/")
      die "refusing to remove '$cache'" ;;
  esac
  [ -d "$cache" ] || { say "nothing to clean at $cache"; return 0; }
  # A receipt store is derived state under a project (or a scratch dir).  It is
  # never a repository, never $HOME, never a filesystem root; if it looks like
  # any of those the path is wrong and removing it would be unrecoverable.
  if [ -e "$cache/.git" ]; then
    die "refusing: '$cache' looks like a repository root"
  fi
  case "$cache" in
    */*/*) ;;
    *) die "refusing: '$cache' is too close to the filesystem root" ;;
  esac
  local all=0 arg
  [ $# -eq 0 ] && all=1
  for arg in "$@"; do [ "$arg" = --all ] && all=1; done
  if [ "$all" -eq 1 ]; then
    find "$cache" -mindepth 1 -maxdepth 1 -type d -exec rm -rf -- {} +
    say "cleaned $cache"
    return 0
  fi
  for arg in "$@"; do
    case "$arg" in
      --all) ;;
      *) if [ -d "$cache/$arg" ]; then rm -rf -- "${cache:?}/$arg"; say "cleaned $arg"; fi ;;
    esac
  done
}

# ── selftest ──────────────────────────────────────────────────────────────
SELF_CHECKS=0
SELF_FAILED=0
check() { # check <description> <0 held, 1 violated>
  SELF_CHECKS=$((SELF_CHECKS + 1))
  if [ "$2" -eq 0 ]; then printf '  ok    %s\n' "$1"
  else printf '  FAIL  %s\n' "$1"; SELF_FAILED=$((SELF_FAILED + 1)); fi
}
is() { [ "$1" -eq 0 ] && echo 0 || echo 1; }

# run_gate ends in `exit` (it IS the program's foreground path).  The selftest
# drives it many times in one process, so give it a subshell of its own.
try_gate() { ( run_gate "$@" ); }

selftest() {
  SCRATCH=$(mktemp -d "${TMPDIR:-/tmp}/gate-receipt-selftest.XXXXXX") || die "mktemp failed"
  local tmp=$SCRATCH PARENT=$SCRATCH/tree ROOT=$SCRATCH/tree/proj
  mkdir -p "$ROOT/src" "$PARENT/sib" "$SCRATCH/.gate-cache"
  printf 'alpha\n' >"$ROOT/src/a.txt"
  printf 'beta\n' >"$ROOT/src/b.txt"
  printf 'proj-makefile\n' >"$ROOT/Makefile"
  printf '(:version "0")\n' >"$ROOT/build-info.sexp"
  printf '(:defsystem "sib")\n' >"$PARENT/sib/sib.asd"
  printf 'defload\n' >"$PARENT/sib/sib.lisp"

  # A fake gate: counts executions, writes a log, exits with a code.
  local FAKE=$SCRATCH/gate.sh
  cat >"$FAKE" <<'EOS'
#!/usr/bin/env bash
# $1 = counter file, $2 = log, $3 = exit code
echo run >>"$1"
{ printf 'fake gate output\n'
  printf ';; Summary:\nPassed:  3\nFailed:  0\n'
} >"$2"
exit "${3:-0}"
EOS
  chmod +x "$FAKE"

  local COUNT=$SCRATCH/count LOG=$SCRATCH/log.txt CACHE=$SCRATCH/.gate-cache
  local opts=( --root "$ROOT" --cache "$CACHE" --log "$LOG"
               --input src --input Makefile
               --siblings "$PARENT" --stamp kind=demo )
  local rc d1 d2 lines out

  echo "== gate-receipt selftest =="

  # ── 1. a red gate is never receipted ───────────────────────────────────
  : >"$COUNT"
  try_gate red "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 1 >/dev/null 2>&1
  rc=$?
  try_gate red "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 1 >/dev/null 2>&1
  lines=$(wc -l <"$COUNT")
  check "1a a failing gate exits non-zero"                     "$(is "$([ "$rc" -ne 0 ] && echo 0 || echo 1)")"
  check "1b a failing gate runs every time (never receipted)"   "$(is "$([ "$lines" -eq 2 ] && echo 0 || echo 1)")"
  check "1c no receipt directory was created for it"            "$(is "$([ ! -d "$CACHE/red" ] && echo 0 || echo 1)")"

  # ── 2/3. a green gate is receipted; a hit does not execute and restores
  #        the log byte-for-byte ──────────────────────────────────────────
  : >"$COUNT"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  rc=$?
  check "2a a passing gate exits 0"                             "$(is "$rc")"
  check "2b the passing gate really executed once"              "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"
  cp -f "$LOG" "$SCRATCH/log.expected"
  : >"$COUNT"
  out=$(try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 2>&1); rc=$?
  check "2c a hit exits 0"                                      "$(is "$rc")"
  check "2d a hit does not execute the command"                  "$(is "$([ ! -s "$COUNT" ] && echo 0 || echo 1)")"
  check "2e a hit says 'cached' and names the log"               "$(is "$(printf '%s' "$out" | grep -q "cached.*$LOG" && echo 0 || echo 1)")"
  check "3  a hit restores the log byte-for-byte"                "$(is "$(cmp -s "$LOG" "$SCRATCH/log.expected" && echo 0 || echo 1)")"
  rm -f "$LOG"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "3b a hit recreates a deleted log byte-for-byte"         "$(is "$(cmp -s "$LOG" "$SCRATCH/log.expected" && echo 0 || echo 1)")"

  # ── 4. one changed byte of one input forces a miss ────────────────────
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  printf 'alpha\nmodified\n' >"$ROOT/src/a.txt"
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "4a a changed input changes the digest"                  "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"
  : >"$COUNT"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "4b a changed input forces a miss (command runs)"        "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"

  # ── 4c. a SIBLING change forces a miss (the (:tree PARENT_DIR) trap) ──
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  printf 'defload2\n' >"$PARENT/sib/sib.lisp"
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "4c a sibling repo change changes the digest"             "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"

  # ── 5. FORCE=1 forces a miss on an identical digest ───────────────────
  : >"$COUNT"
  FORCE=1 try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "5  FORCE=1 executes despite a matching receipt"          "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"

  # ── 6. clean empties the store; the next run executes ─────────────────
  clean_cache "$CACHE" --all >/dev/null 2>&1
  check "6a cache-clean removes the receipts"                     "$(is "$([ -z "$(find "$CACHE" -mindepth 1 -maxdepth 1 -type d)" ] && echo 0 || echo 1)")"
  : >"$COUNT"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "6b the run after a clean executes again"                 "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"

  # ── 7. build-info.sexp is regenerated every run: not an input ─────────
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  printf '(:version "9" :git-sha "deadbee" :git-dirty "dirty")\n' >"$ROOT/build-info.sexp"
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "7  regenerating build-info.sexp does not change the digest" \
        "$(is "$([ "$d1" = "$d2" ] && echo 0 || echo 1)")"

  # ── 8. the digest is deterministic ────────────────────────────────────
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "8  the digest is deterministic"                          "$(is "$([ "$d1" = "$d2" ] && echo 0 || echo 1)")"

  # ── 9. a variant stamp distinguishes otherwise identical gates ────────
  d1=$(digest_gate green "${opts[@]}" --stamp variant=one 2>/dev/null)
  d2=$(digest_gate green "${opts[@]}" --stamp variant=two 2>/dev/null)
  check "9  an extra stamp changes the digest"                    "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"

  # ── 10. a cache that cannot be written must not break the gate ────────
  : >"$SCRATCH/notadir"
  : >"$COUNT"
  try_gate readonly "${opts[@]}" --cache "$SCRATCH/notadir" \
    -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  rc=$?
  check "10 an unwritable cache still runs the gate and exits 0"  \
        "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && [ "$rc" -eq 0 ] && echo 0 || echo 1)")"

  echo ""
  if [ "$SELF_FAILED" -eq 0 ]; then
    echo "== gate-receipt selftest: $SELF_CHECKS checks, 0 failed =="
    return 0
  fi
  echo "== gate-receipt selftest: $SELF_CHECKS checks, $SELF_FAILED FAILED =="
  return 1
}

# ── main ──────────────────────────────────────────────────────────────────
[ $# -gt 0 ] || { usage; exit 2; }
sub=$1; shift
case "$sub" in
  help|--help|-h) usage ;;
  run)      run_gate "$@" ;;
  digest)   digest_gate "$@" ;;
  selftest) selftest ;;
  status)
    CACHE_ARG=$PWD/.gate-cache
    while [ $# -gt 0 ]; do
      case "$1" in
        --cache)      CACHE_ARG=${2:-}; [ -n "$CACHE_ARG" ] || die "--cache needs a value"; shift 2 ;;
        --verbose|-v) VERBOSE=1; shift ;;
        *) die "unknown option $1" ;;
      esac
    done
    status_cache "$CACHE_ARG" ;;
  clean)
    CACHE_ARG=$PWD/.gate-cache
    GATES=()
    while [ $# -gt 0 ]; do
      case "$1" in
        --cache) CACHE_ARG=${2:-}; [ -n "$CACHE_ARG" ] || die "--cache needs a value"; shift 2 ;;
        --all)   GATES+=(--all); shift ;;
        *)       GATES+=("$1"); shift ;;
      esac
    done
    clean_cache "$CACHE_ARG" "${GATES[@]+"${GATES[@]}"}" ;;
  *) usage; exit 2 ;;
esac
