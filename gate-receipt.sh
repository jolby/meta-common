#!/usr/bin/env bash
# gate-receipt.sh — incremental gate receipts (bd-sbf).
#
# A gate is a make target that ends in a verdict: `make test`, `make
# demos-dl-parity`, `make capture-corpus-check`.  Running one costs seconds to
# minutes, and most runs re-decide a question whose inputs did not change since
# the last green answer.  A *receipt* records one green run against a digest of
# its declared inputs; a later run with the same digest restores the log and
# the verdict without executing anything.
#
# INVARIANTS (breaking one is worse than being slow)
#   1. A false hit is worse than a slow miss.  The digest errs WIDE: when in
#      doubt include the file, include the repo, include the environment.
#   2. Only exit 0 is receipted.  A red gate always re-runs, so a receipt can
#      never turn a red gate green.
#   3. The inspection surface survives.  A hit restores the recorded
#      <target>-LATEST.txt byte-for-byte and prints where it is (AGENTS.md:
#      inspect the log, never re-run to look).
#   4. The receipt records the TARGET's exit code, not an inner command's.
#      This is by construction: `run` wraps the whole `*-uncached` target.
#   5. The cache is machine-local derived state, never committed.
#   6. A green gate must SAY it judged something.  A gate declares the text its
#      log carries only when a run that actually concluded (--require-log-match);
#      when it does, exit 0 with no such line is NOT receipted and NOT green.
#      Exit status is not evidence — the log is.  bd-829: a compile error in
#      `make test` echoed the shared target's own no-test-system guard into the
#      SBCL backtrace, the recipe took its "nothing to judge" exit-0 branch, and
#      a build that compiled nothing was receipted GREEN; the next identical run
#      answered "cached … PASS" without executing anything.  Invariant 2 could
#      not see it because the gate really did exit 0.
#
# THE SHAPE IN cl-project.mk
#   test:            @$(GATE_RECEIPT) run test --log <out> -- $(MAKE) --no-print-directory test-uncached
#   test-uncached:   <the recipe exactly as it was before>
# On a miss the target behaves exactly as it did before receipts existed (same
# capture-output, same LATEST log, same verdict), so adopting receipts cannot
# move a verdict through a changed recipe.
#
# USAGE
#   gate-receipt run    GATE --log PATH [opts] -- CMD...
#   gate-receipt digest GATE [opts] [--verbose]
#   gate-receipt why    GATE [opts]
#   gate-receipt status [--cache DIR] [--verbose]
#   gate-receipt clean  [--cache DIR] [--all | GATE...]
#   gate-receipt selftest
#
#   opts: --root DIR            project root (default: .)
#         --cache DIR           receipt store (default: ROOT/.gate-cache)
#         --input PATH          file or dir, relative to ROOT (repeatable)
#         --exclude GLOB        extra basename glob to skip (repeatable)
#         --siblings DIR        walk sibling repos (dirs holding an *.asd)
#         --no-siblings         do not walk them
#         --stamp NAME=VALUE    extra digest input (repeatable)
#         --stamp-env NAME      digest input read from the environment
#         --sbcl PATH           stamp PATH and its --version
#         --cache-version N     bump to invalidate every receipt
#         --require-log-match ERE  a green run must leave this in its log, or it
#                               is not receipted and the gate fails (invariant 6)
#         --verbose             digest: print the manifest
#
#   env: FORCE=1  behave as a miss even on an identical digest.
#
# WHAT IS EXCLUDED, AND WHY (do not "simplify" these away)
#   build-info.sexp   regenerated by every make run; including it means no
#                     receipt ever hits (the trap that silently disables this)
#   *.fasl, .git      derived
#   work/ tmp/        run outputs; gitignored in every adopting repo
#   .gate-cache/      the receipts themselves (otherwise: never hits again)
# A project whose source lives in a directory with one of those names overrides
# with GATE_EXCLUDES in its Makefile; do not widen the defaults for everyone.
#
# SIBLING REPOS ARE INPUTS.  cl-project.mk initialises ASDF with
# (:tree PARENT_DIR), so a test can load a changed sibling checkout.  A sibling
# change that is not in the digest is a silent false hit.  Siblings are walked
# with an allow-list of file types (Lisp source and the data a Lisp program
# reads) because a full walk of this repos/ tree is ~38 GB of build output.

set -uo pipefail

PROG=gate-receipt
CACHE_VERSION_DEFAULT=1

# Basename globs pruned from every walk.
DEFAULT_EXCLUDES=(
  .git .gate-cache
  '*.fasl' '*.dfsl' '*.fas' '*.lib' '*.x86f' '*.amd64f' '*.lx64fsl'
  build-info.sexp
  work tmp .dart_tool node_modules .cache .pytest_cache
  '*.db' '*.db-journal' '*.db-wal' '*.db-shm'
)

# What a sibling repo contributes.  Lisp source plus the data files a Lisp
# program reads (fonts, icon tables, JSON theme tokens).  A binary asset that
# is NOT here is still covered when the root project owns it: the root is
# walked in full.
SIBLING_EXTS=(
  '*.lisp' '*.asd' '*.asdf' '*.cl' '*.sexp' '*.lsp'
  '*.json' '*.edn' '*.csv' '*.ttf' '*.otf' '*.ttc' '*.png' '*.svg' '*.jpg'
  '*.dart' '*.yaml' '*.yml'
)

TMPFILES=()
SCRATCH=
die() { printf '%s: %s\n' "$PROG" "$*" >&2; exit 2; }
say() { printf '%s: %s\n' "$PROG" "$*"; }

cleanup() {
  local f
  for f in "${TMPFILES[@]+"${TMPFILES[@]}"}"; do rm -f -- "$f"; done
  if [ -n "$SCRATCH" ] && [ -d "$SCRATCH" ]; then rm -rf -- "$SCRATCH"; fi
}
trap cleanup EXIT

tmpfile() {
  local f
  f=$(mktemp "${TMPDIR:-/tmp}/gate-receipt-$1.XXXXXX") || die "mktemp failed"
  TMPFILES+=("$f")
  printf '%s' "$f"
}

now_ms() { date +%s%3N; }
short8() { printf '%.8s' "$1"; }

usage() { sed -n '2,80p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

# ── digest ────────────────────────────────────────────────────────────────
GATE=
ROOT=$PWD
CACHE=
LOG=
CACHE_VERSION=$CACHE_VERSION_DEFAULT
VERBOSE=0
SIBLINGS=
WALK_SIBLINGS=1
SBCL_BIN=
INPUTS=()
EXCLUDES=()
STAMPS=()
STAMP_ENVS=()
REQUIRE_LOG_MATCH=
MISSING=()
MANIFEST=
DIGEST=
CMDSTR=

# parse_opts <args...> — consumes recognised options; sets OPT_LEFT to the
# first argument it did not consume (the caller decides what that means).
parse_opts() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --root)          ROOT=${2:-}; [ -n "$ROOT" ] || die "--root needs a value"; shift 2 ;;
      --cache)         CACHE=${2:-}; [ -n "$CACHE" ] || die "--cache needs a value"; shift 2 ;;
      --log)           LOG=${2:-}; [ -n "$LOG" ] || die "--log needs a value"; shift 2 ;;
      --input)         INPUTS+=("${2:-}"); shift 2 ;;
      --exclude)       EXCLUDES+=("${2:-}"); shift 2 ;;
      --stamp)         STAMPS+=("${2:-}"); shift 2 ;;
      --stamp-env)     STAMP_ENVS+=("${2:-}"); shift 2 ;;
      --require-log-match) REQUIRE_LOG_MATCH=${2:-}; [ -n "$REQUIRE_LOG_MATCH" ] || die "--require-log-match needs a value"; shift 2 ;;
      --siblings)      SIBLINGS=${2:-}; [ -n "$SIBLINGS" ] || die "--siblings needs a value"; shift 2 ;;
      --no-siblings)   WALK_SIBLINGS=0; shift ;;
      --sbcl)          SBCL_BIN=${2:-}; [ -n "$SBCL_BIN" ] || die "--sbcl needs a value"; shift 2 ;;
      --cache-version) CACHE_VERSION=${2:-}; [ -n "$CACHE_VERSION" ] || die "--cache-version needs a value"; shift 2 ;;
      --verbose|-v)    VERBOSE=1; shift ;;
      *)               return 1 ;;
    esac
  done
  return 0
}

abs_under_root() {
  case "$1" in
    /*) printf '%s' "$1" ;;
    *)  printf '%s/%s' "$ROOT" "$1" ;;
  esac
}

# find(1) prefix that prunes the exclusion globs at any depth.
# A glob with a slash is a PATH (relative to whatever is being walked), e.g.
# dart/build, so it cannot hide a directory of the same name elsewhere; a bare
# glob is a basename, e.g. *.fasl.
prune_args() {
  local first=1 g
  PRUNE=( \( )
  for g in "${DEFAULT_EXCLUDES[@]}" "${EXCLUDES[@]+"${EXCLUDES[@]}"}"; do
    [ "$first" -eq 1 ] || PRUNE+=( -o )
    case "$g" in
      */*) PRUNE+=( -path "*/$g" ) ;;
      *)   PRUNE+=( -name "$g" ) ;;
    esac
    first=0
  done
  PRUNE+=( \) -prune -o )
}

sibling_ext_args() {
  local first=1 e
  EXT_ARGS=( \( )
  for e in "${SIBLING_EXTS[@]}"; do
    [ "$first" -eq 1 ] || EXT_ARGS+=( -o )
    EXT_ARGS+=( -name "$e" )
    first=0
  done
  EXT_ARGS+=( \) )
}

# build_manifest — writes the manifest to $MANIFEST and sets $DIGEST.
build_manifest() {
  local list hashes nfiles nhashes abs p m s v dist
  list=$(tmpfile files)
  hashes=$(tmpfile hash)

  prune_args
  sibling_ext_args

  : >"$list"
  MISSING=()
  for p in "${INPUTS[@]+"${INPUTS[@]}"}"; do
    abs=$(abs_under_root "$p")
    if [ -f "$abs" ]; then
      printf '%s\0' "$abs" >>"$list"
    elif [ -d "$abs" ]; then
      find "$abs" "${PRUNE[@]}" -type f -print0 >>"$list"
    else
      # A declared input that does not exist yet: record it, so creating it
      # later changes the digest instead of being invisible.
      MISSING+=("$p")
    fi
  done

  if [ "$WALK_SIBLINGS" -eq 1 ] && [ -n "$SIBLINGS" ] && [ -d "$SIBLINGS" ]; then
    local sib
    for sib in "$SIBLINGS"/*; do
      [ -d "$sib" ] || continue
      [ "$sib" -ef "$ROOT" ] && continue
      compgen -G "$sib/*.asd" >/dev/null || continue
      find "$sib" "${PRUNE[@]}" -type f "${EXT_ARGS[@]}" -print0 >>"$list"
    done
  fi

  LC_ALL=C sort -zu -o "$list" "$list"
  nfiles=$(tr -dc '\0' <"$list" | wc -c)
  # One sha256sum process per batch, input order preserved; the file list is
  # already sorted, so the records come out sorted by path.
  xargs -0 -r sha256sum --zero <"$list" >"$hashes" 2>/dev/null
  nhashes=$(tr -dc '\0' <"$hashes" | wc -c)

  MANIFEST=$(tmpfile manifest)
  {
    printf 'cache_version=%s\n' "$CACHE_VERSION"
    printf 'gate=%s\n' "$GATE"
    # The conclusion a green run must leave behind is part of the gate's
    # DEFINITION: a receipt restored under a looser requirement says less than
    # the gate now claims, which is the same false green by another road.
    printf 'require_log_match=%s\n' "$REQUIRE_LOG_MATCH"
    printf 'cmd=%s\n' "$CMDSTR"
    tr '\0' '\n' <"$hashes" | awk '{ print "file " substr($1,1,64) " " substr($0,67) }'
    for m in "${MISSING[@]+"${MISSING[@]}"}"; do printf 'missing %s\n' "$m"; done
    {
      for s in "${STAMPS[@]+"${STAMPS[@]}"}"; do printf '%s\n' "$s"; done
      for v in "${STAMP_ENVS[@]+"${STAMP_ENVS[@]}"}"; do printf '%s=%s\n' "$v" "${!v-}"; done
      if [ -n "$SBCL_BIN" ]; then
        printf 'sbcl=%s\n' "$SBCL_BIN"
        printf 'sbcl_version=%s\n' "$("$SBCL_BIN" --version 2>&1 | head -1)"
      fi
      dist=$HOME/quicklisp/dists/quicklisp/distinfo.txt
      if [ -f "$dist" ]; then
        printf 'ql_dist=%s\n' "$(sha256sum "$dist" | cut -c1-16)"
      fi
      printf 'asdf_source_registry=%s\n' "${ASDF_SOURCE_REGISTRY-}"
      printf 'sbcl_home=%s\n' "${SBCL_HOME-}"
    } | LC_ALL=C sort | sed 's/^/stamp /'
    if [ "$nfiles" -ne "$nhashes" ]; then
      # A file vanished mid-walk (concurrent build).  Never let that read as a
      # stable tree: this line forces a miss.
      printf 'unstable=%s-%s\n' "$(date +%s%N)" "$RANDOM"
    fi
  } >"$MANIFEST"

  DIGEST=$(sha256sum "$MANIFEST" | cut -c1-64)
}

# ── run ───────────────────────────────────────────────────────────────────
run_gate() {
  GATE=${1:-}
  [ -n "$GATE" ] || die "run needs a gate name"
  shift
  local -a cmd=()
  local seen_dd=0
  while [ $# -gt 0 ]; do
    if [ "$seen_dd" -eq 1 ]; then cmd+=("$1"); shift; continue; fi
    case "$1" in
      --) seen_dd=1; shift ;;
      --root|--cache|--log|--input|--exclude|--stamp|--stamp-env|--siblings|--sbcl|--cache-version|--require-log-match)
        [ $# -ge 2 ] || die "$1 needs a value"
        parse_opts "$1" "$2" || die "bad option $1"
        shift 2 ;;
      --no-siblings|--verbose|-v)
        parse_opts "$1" || die "bad option $1"
        shift ;;
      *) die "unknown option '$1' (put the command after --)" ;;
    esac
  done
  [ "$seen_dd" -eq 1 ] || die "run needs '--' before the command"
  [ ${#cmd[@]} -gt 0 ] || die "run needs a command after '--'"

  ROOT=$(cd "$ROOT" && pwd) || die "no such root"
  [ -n "$CACHE" ] || CACHE=$ROOT/.gate-cache
  [ -n "$LOG" ] || die "run needs --log PATH (the file a hit must restore)"
  CMDSTR="${cmd[*]}"

  build_manifest
  local dir=$CACHE/$GATE/$DIGEST
  local d8; d8=$(short8 "$DIGEST")

  if [ -f "$dir/code" ] && [ -z "${FORCE-}" ]; then
    local code; code=$(cat "$dir/code")
    if [ "$code" = 0 ]; then
      if [ -f "$dir/log" ]; then
        cp -f "$dir/log" "$LOG"
        printf '%s: cached (%ss, %s) — log: %s\n' \
          "$GATE" "$(cat "$dir/elapsed" 2>/dev/null || echo '?')" "$d8" "$LOG"
        local v
        # The gate's own last word: "=== VERDICT: PASS ===" for the test
        # targets, "<gate>: N demo(s), PASS" for the parity gates, "All tests
        # passed!" for the Dart one.  Printing only "cached" would tell a
        # reader the log exists but not what it says.
        v=$(grep -v '^[[:space:]]*$' "$LOG" 2>/dev/null | tail -1)
        [ -n "$v" ] && printf '  %s\n' "$v"
        exit 0
      elif [ "$(cat "$dir/log_state" 2>/dev/null)" = none ]; then
        rm -f "$LOG"
        printf '%s: cached (%ss, %s) — no log for this gate\n' \
          "$GATE" "$(cat "$dir/elapsed" 2>/dev/null || echo '?')" "$d8"
        exit 0
      else
        # A receipt whose log is gone cannot honour invariant 3: re-run.
        say "$GATE: receipt $d8 lost its log — re-running"
      fi
    else
      # Should never exist (only green is receipted); if it does, ignore it.
      say "$GATE: discarding non-green receipt $d8"
      rm -rf -- "$dir"
    fi
  elif [ -f "$dir/code" ]; then
    say "$GATE: FORCE set — re-running despite receipt $d8"
  fi

  local t0 t1 rc elapsed secs tmp
  t0=$(now_ms)
  "${cmd[@]}"
  rc=$?
  t1=$(now_ms)
  elapsed=$((t1 - t0))
  secs=$(printf '%d.%d' "$((elapsed / 1000))" "$((elapsed % 1000 / 100))")

  if [ "$rc" -ne 0 ]; then
    # Invariant 2: nothing is written for a red gate.
    exit "$rc"
  fi

  # Invariant 6.  Exit 0 only means the recipe said so; a gate whose log holds
  # none of the text a concluded run writes judged NOTHING.  The instance this
  # was found on (bd-829) exited 0 because a diagnostic STRING appeared in an
  # SBCL backtrace, so the check cannot be "the log mentions X": it is the text
  # the gate's own verdict writes, and callers anchor it with ^ so a backtrace's
  # echo of source text (mid-line, indented) cannot satisfy it.
  if [ -n "$REQUIRE_LOG_MATCH" ]; then
    if [ ! -f "$LOG" ]; then
      say "$GATE: green but there is no log at $LOG — nothing says it judged"
      say "$GATE: NOT receipted; treat this run as FAILED"
      exit 1
    fi
    if ! grep -qE -- "$REQUIRE_LOG_MATCH" "$LOG"; then
      say "$GATE: green, but the log holds no line matching '$REQUIRE_LOG_MATCH'"
      say "$GATE: the gate judged NOTHING (a build that never reached its verdict
      looks exactly like this) — NOT receipted; treat this run as FAILED."
      say "$GATE: the log to read is $LOG"
      exit 1
    fi
  fi

  mkdir -p "$CACHE/$GATE" 2>/dev/null || { say "$GATE: cache not writable — not recorded"; exit 0; }
  tmp=$(mktemp -d "$CACHE/$GATE/.tmp.XXXXXX") || { say "$GATE: mktemp failed — not recorded"; exit 0; }
  printf '%s\n' "$rc" >"$tmp/code"
  printf '%s\n' "$elapsed" >"$tmp/elapsed_ms"
  printf '%s\n' "$secs" >"$tmp/elapsed"
  printf '%s\n' "$(date -Iseconds)" >"$tmp/recorded"
  printf '%s\n' "$CMDSTR" >"$tmp/cmd"
  cp -f "$MANIFEST" "$tmp/manifest"
  if [ -f "$LOG" ]; then
    cp -f "$LOG" "$tmp/log"
    printf 'file\n' >"$tmp/log_state"
    printf '%s\n' "$LOG" >"$tmp/log_path"
  else
    printf 'none\n' >"$tmp/log_state"
  fi
  rm -rf -- "$dir"
  mv -T "$tmp" "$dir" || { say "$GATE: could not install receipt"; exit 0; }
  printf '%s\n' "$DIGEST" >"$CACHE/$GATE/LATEST"
  printf '%s: receipt %s written (green, %ss) — log: %s\n' "$GATE" "$d8" "$secs" "$LOG"
  exit 0
}

# ── digest (diagnostic) ───────────────────────────────────────────────────
digest_gate() {
  GATE=${1:-}
  [ -n "$GATE" ] || die "digest needs a gate name"
  shift
  parse_opts "$@" || die "bad option"
  ROOT=$(cd "$ROOT" && pwd) || die "no such root: $ROOT"
  [ ${#INPUTS[@]} -gt 0 ] || die "digest needs at least one --input"
  build_manifest
  printf '%s\n' "$DIGEST"
  if [ "$VERBOSE" -eq 1 ]; then
    printf '%s\n' '--- manifest ---'
    cat "$MANIFEST"
  fi
  exit 0
}

# ── why (diagnostic: did the newest receipt miss, and on WHICH input) ─────
#
# The question a stale receipt costs a re-run to answer, until now.  A gate's
# digest walks the project AND every sibling repo (ASDF loads them through
# `:tree`), so ANYONE's save invalidates EVERYONE's receipts — correctly, because
# a false hit is the one failure this tool must never have.  But a bare `miss`
# cannot tell you whether the change can possibly affect THIS gate, so the only
# safe-looking move is to run it.  That is how a workstation ends up pegged for
# twenty minutes (bd-eto).
#
# This mode compares the newest receipt's manifest against the tree as it is NOW
# and names what moved.  It EXECUTES NOTHING and WRITES NOTHING, so it is the
# thing to run first: `make cache-why` costs ~0.4 s per gate.
#
# THE CMD LINE IS READ FROM THE RECEIPT, not from this command line.  `cmd=` is
# part of the manifest (it names the recipe a receipt was made from), and `why`
# is given no command — so it echoes the receipt's, which is what makes the two
# digests comparable.  A change to the make RECIPE still shows up, as a changed
# `Makefile` input, which is what it is.
manifest_diff() {
  # One line per difference: "M path" changed, "A path" added since, "R path"
  # removed since, "S key" a non-file manifest line that differs.
  awk '
    FNR==NR {
      if ($1=="file") old[$3]=$2
      else if ($1!="cmd") olds[$0]=1
      next
    }
    $1=="file" { cur[$3]=$2; next }
    $1!="cmd"  { curs[$0]=1 }
    END {
      for (p in cur) {
        if (!(p in old))      print "A " p
        else if (old[p]!=cur[p]) print "M " p
      }
      for (p in old) if (!(p in cur)) print "R " p
      for (k in curs) if (!(k in olds)) print "S " k
      for (k in olds) if (!(k in curs)) print "S " k
    }
  ' "$1" "$2" | LC_ALL=C sort -k2
}

why_gate() {
  GATE=${1:-}
  [ -n "$GATE" ] || die "why needs a gate name"
  shift
  parse_opts "$@" || die "bad option"
  ROOT=$(cd "$ROOT" && pwd) || die "no such root: $ROOT"
  [ ${#INPUTS[@]} -gt 0 ] || die "why needs at least one --input"
  [ -n "$CACHE" ] || CACHE=$ROOT/.gate-cache

  local latest dir rec logp diff nchanged nadded nremoved nstamp
  latest=$(cat "$CACHE/$GATE/LATEST" 2>/dev/null)
  dir=$CACHE/$GATE/$latest
  if [ -z "$latest" ] || [ ! -f "$dir/manifest" ]; then
    printf '%-22s %s\n' "$GATE" "no receipt — nothing to compare (run it once)"
    return 0
  fi
  rec=$(cat "$dir/recorded" 2>/dev/null || echo '?')
  logp=$(cat "$dir/log_path" 2>/dev/null || echo '(none)')

  CMDSTR=$(cat "$dir/cmd" 2>/dev/null || echo '')
  build_manifest

  if [ "$DIGEST" = "$latest" ]; then
    printf '%-22s %s  %s  log: %s\n' "$GATE" "cached" "$(short8 "$latest")" "$logp"
    return 0
  fi

  diff=$(manifest_diff "$dir/manifest" "$MANIFEST" \
         | sed -e 's|/\./|/|g' \
               -e "s|$(dirname "$ROOT")/||g" -e "s|$ROOT/||g" \
         | LC_ALL=C sort -u)
  nchanged=$(printf '%s\n' "$diff" | grep -c '^M ')
  nadded=$(printf '%s\n' "$diff" | grep -c '^A ')
  nremoved=$(printf '%s\n' "$diff" | grep -c '^R ')
  nstamp=$(printf '%s\n' "$diff" | grep -c '^S ')
  printf '%-22s %s  %s  recorded %s  log: %s\n' \
    "$GATE" "STALE" "$(short8 "$latest")" "$rec" "$logp"
  printf '  %d changed, %d added, %d removed, %d stamp(s) since that receipt:\n' \
    "$nchanged" "$nadded" "$nremoved" "$nstamp"
  # Eight is enough to recognise the culprit (the usual answer is "another
  # agent landed in a sibling repo") and short enough to read at a glance.
  printf '%s\n' "$diff" | grep . | head -8 | while IFS= read -r line; do
    printf '    %s\n' "$line"
  done
  n=$(printf '%s\n' "$diff" | grep -c .)
  [ "$n" -gt 8 ] && printf '    ... and %d more\n' "$((n - 8))"
  printf '  Nothing was executed and nothing was written. A miss is CORRECT when\n'
  printf '  one of these can change this gate\x27s answer; run it only then.\n'
  return 0
}

# ── status / clean ────────────────────────────────────────────────────────
status_cache() {
  local cache=$1
  [ -d "$cache" ] || { say "no receipts at $cache"; return 0; }
  local g
  printf '%-22s %-10s %-20s %8s %s\n' GATE DIGEST RECORDED ELAPSED LOG
  for g in "$cache"/*; do
    [ -d "$g" ] || continue
    [ -f "$g/LATEST" ] || continue
    local name d dir rec elapsed logp n
    name=$(basename "$g")
    d=$(cat "$g/LATEST")
    dir=$g/$d
    rec=$(cat "$dir/recorded" 2>/dev/null || echo '?')
    elapsed=$(cat "$dir/elapsed" 2>/dev/null || echo '?')
    logp=$(cat "$dir/log_path" 2>/dev/null || echo '(none)')
    n=$(find "$g" -mindepth 1 -maxdepth 1 -type d ! -name '.tmp*' | wc -l)
    printf '%-22s %-10s %-20s %8s %s\n' "$name" "$(short8 "$d")" "$rec" "$elapsed" "$logp"
    if [ "$VERBOSE" -eq 1 ]; then
      printf '  receipts: %s  manifest: %s\n' "$n" "$dir/manifest"
    fi
  done
}

clean_cache() {
  local cache=$1; shift
  case "$cache" in
    ''|'/'|'/tmp'|'/home'|'/usr'|'/var'|'/etc'|"$HOME"|"$HOME/")
      die "refusing to remove '$cache'" ;;
  esac
  [ -d "$cache" ] || { say "nothing to clean at $cache"; return 0; }
  # A receipt store is derived state under a project (or a scratch dir).  It is
  # never a repository, never $HOME, never a filesystem root; if it looks like
  # any of those the path is wrong and removing it would be unrecoverable.
  if [ -e "$cache/.git" ]; then
    die "refusing: '$cache' looks like a repository root"
  fi
  case "$cache" in
    */*/*) ;;
    *) die "refusing: '$cache' is too close to the filesystem root" ;;
  esac
  local all=0 arg
  [ $# -eq 0 ] && all=1
  for arg in "$@"; do [ "$arg" = --all ] && all=1; done
  if [ "$all" -eq 1 ]; then
    find "$cache" -mindepth 1 -maxdepth 1 -type d -exec rm -rf -- {} +
    say "cleaned $cache"
    return 0
  fi
  for arg in "$@"; do
    case "$arg" in
      --all) ;;
      *) if [ -d "$cache/$arg" ]; then rm -rf -- "${cache:?}/$arg"; say "cleaned $arg"; fi ;;
    esac
  done
}

# ── selftest ──────────────────────────────────────────────────────────────
SELF_CHECKS=0
SELF_FAILED=0
check() { # check <description> <0 held, 1 violated>
  SELF_CHECKS=$((SELF_CHECKS + 1))
  if [ "$2" -eq 0 ]; then printf '  ok    %s\n' "$1"
  else printf '  FAIL  %s\n' "$1"; SELF_FAILED=$((SELF_FAILED + 1)); fi
}
is() { [ "$1" -eq 0 ] && echo 0 || echo 1; }

# run_gate ends in `exit` (it IS the program's foreground path).  The selftest
# drives it many times in one process, so give it a subshell of its own.
try_gate() { ( run_gate "$@" ); }

selftest() {
  SCRATCH=$(mktemp -d "${TMPDIR:-/tmp}/gate-receipt-selftest.XXXXXX") || die "mktemp failed"
  local tmp=$SCRATCH PARENT=$SCRATCH/tree ROOT=$SCRATCH/tree/proj
  mkdir -p "$ROOT/src" "$PARENT/sib" "$SCRATCH/.gate-cache"
  printf 'alpha\n' >"$ROOT/src/a.txt"
  printf 'beta\n' >"$ROOT/src/b.txt"
  printf 'proj-makefile\n' >"$ROOT/Makefile"
  printf '(:version "0")\n' >"$ROOT/build-info.sexp"
  printf '(:defsystem "sib")\n' >"$PARENT/sib/sib.asd"
  printf 'defload\n' >"$PARENT/sib/sib.lisp"

  # A fake gate: counts executions, writes a log, exits with a code.
  local FAKE=$SCRATCH/gate.sh
  cat >"$FAKE" <<'EOS'
#!/usr/bin/env bash
# $1 = counter file, $2 = log, $3 = exit code
echo run >>"$1"
{ printf 'fake gate output\n'
  printf ';; Summary:\nPassed:  3\nFailed:  0\n'
} >"$2"
exit "${3:-0}"
EOS
  chmod +x "$FAKE"

  local COUNT=$SCRATCH/count LOG=$SCRATCH/log.txt CACHE=$SCRATCH/.gate-cache
  local opts=( --root "$ROOT" --cache "$CACHE" --log "$LOG"
               --input src --input Makefile
               --siblings "$PARENT" --stamp kind=demo )
  local rc d1 d2 lines out

  echo "== gate-receipt selftest =="

  # ── 1. a red gate is never receipted ───────────────────────────────────
  : >"$COUNT"
  try_gate red "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 1 >/dev/null 2>&1
  rc=$?
  try_gate red "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 1 >/dev/null 2>&1
  lines=$(wc -l <"$COUNT")
  check "1a a failing gate exits non-zero"                     "$(is "$([ "$rc" -ne 0 ] && echo 0 || echo 1)")"
  check "1b a failing gate runs every time (never receipted)"   "$(is "$([ "$lines" -eq 2 ] && echo 0 || echo 1)")"
  check "1c no receipt directory was created for it"            "$(is "$([ ! -d "$CACHE/red" ] && echo 0 || echo 1)")"

  # ── 2/3. a green gate is receipted; a hit does not execute and restores
  #        the log byte-for-byte ──────────────────────────────────────────
  : >"$COUNT"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  rc=$?
  check "2a a passing gate exits 0"                             "$(is "$rc")"
  check "2b the passing gate really executed once"              "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"
  cp -f "$LOG" "$SCRATCH/log.expected"
  : >"$COUNT"
  out=$(try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 2>&1); rc=$?
  check "2c a hit exits 0"                                      "$(is "$rc")"
  check "2d a hit does not execute the command"                  "$(is "$([ ! -s "$COUNT" ] && echo 0 || echo 1)")"
  check "2e a hit says 'cached' and names the log"               "$(is "$(printf '%s' "$out" | grep -q "cached.*$LOG" && echo 0 || echo 1)")"
  check "2f a hit repeats the log's last line (its verdict)"      "$(is "$(printf '%s' "$out" | grep -q 'Failed:  0' && echo 0 || echo 1)")"
  check "3  a hit restores the log byte-for-byte"                "$(is "$(cmp -s "$LOG" "$SCRATCH/log.expected" && echo 0 || echo 1)")"
  rm -f "$LOG"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "3b a hit recreates a deleted log byte-for-byte"         "$(is "$(cmp -s "$LOG" "$SCRATCH/log.expected" && echo 0 || echo 1)")"

  # ── 4. one changed byte of one input forces a miss ────────────────────
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  printf 'alpha\nmodified\n' >"$ROOT/src/a.txt"
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "4a a changed input changes the digest"                  "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"
  : >"$COUNT"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "4b a changed input forces a miss (command runs)"        "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"

  # ── 4c. a SIBLING change forces a miss (the (:tree PARENT_DIR) trap) ──
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  printf 'defload2\n' >"$PARENT/sib/sib.lisp"
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "4c a sibling repo change changes the digest"             "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"

  # ── 4d-4i. `why`: WHICH input invalidated the receipt (bd-eto) ─────────
  # The digest is wide ON PURPOSE (the project and every sibling repo, because
  # ASDF loads them through :tree), so a miss is usually somebody else's
  # landing.  The missing half was the next question — WHICH input moved, and
  # can it change this gate's answer — and without it the only safe-looking move
  # is to re-run, which is how a workstation ends up pegged.  These pin that
  # `why` answers it, executes nothing, and writes nothing.
  local before
  out=$(why_gate green "${opts[@]}" 2>&1)
  check "4d why reports STALE after a sibling change"             \
        "$(is "$(printf '%s' "$out" | grep -q 'STALE' && echo 0 || echo 1)")"
  check "4e why NAMES the input that moved"                       \
        "$(is "$(printf '%s' "$out" | grep -q 'sib\.lisp' && echo 0 || echo 1)")"
  : >"$COUNT"
  why_gate green "${opts[@]}" >/dev/null 2>&1
  check "4f why executes nothing"                                 \
        "$(is "$([ ! -s "$COUNT" ] && echo 0 || echo 1)")"
  before=$(cat "$CACHE/green/LATEST")
  why_gate green "${opts[@]}" >/dev/null 2>&1
  check "4g why writes no receipt (LATEST unchanged)"             \
        "$(is "$([ "$(cat "$CACHE/green/LATEST")" = "$before" ] && echo 0 || echo 1)")"
  # Make the receipt current again: the same question must then answer "cached",
  # or `why` would be a pessimist nobody could use to skip a run.
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  out=$(why_gate green "${opts[@]}" 2>&1)
  check "4h why says cached when the digest matches"              \
        "$(is "$(printf '%s' "$out" | grep -q 'cached' && echo 0 || echo 1)")"
  out=$(why_gate nosuchgate "${opts[@]}" 2>&1); rc=$?
  check "4i why on a gate with no receipt says so, and exits 0"   \
        "$(is "$(printf '%s' "$out" | grep -q 'no receipt' && [ "$rc" -eq 0 ] && echo 0 || echo 1)")"

  # ── 5. FORCE=1 forces a miss on an identical digest ───────────────────
  : >"$COUNT"
  FORCE=1 try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "5  FORCE=1 executes despite a matching receipt"          "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"

  # ── 6. clean empties the store; the next run executes ─────────────────
  clean_cache "$CACHE" --all >/dev/null 2>&1
  check "6a cache-clean removes the receipts"                     "$(is "$([ -z "$(find "$CACHE" -mindepth 1 -maxdepth 1 -type d)" ] && echo 0 || echo 1)")"
  : >"$COUNT"
  try_gate green "${opts[@]}" -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  check "6b the run after a clean executes again"                 "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && echo 0 || echo 1)")"

  # ── 7. build-info.sexp is regenerated every run: not an input ─────────
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  printf '(:version "9" :git-sha "deadbee" :git-dirty "dirty")\n' >"$ROOT/build-info.sexp"
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "7  regenerating build-info.sexp does not change the digest" \
        "$(is "$([ "$d1" = "$d2" ] && echo 0 || echo 1)")"

  # ── 8. the digest is deterministic ────────────────────────────────────
  d1=$(digest_gate green "${opts[@]}" 2>/dev/null)
  d2=$(digest_gate green "${opts[@]}" 2>/dev/null)
  check "8  the digest is deterministic"                          "$(is "$([ "$d1" = "$d2" ] && echo 0 || echo 1)")"

  # ── 9. a variant stamp distinguishes otherwise identical gates ────────
  d1=$(digest_gate green "${opts[@]}" --stamp variant=one 2>/dev/null)
  d2=$(digest_gate green "${opts[@]}" --stamp variant=two 2>/dev/null)
  check "9  an extra stamp changes the digest"                    "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"

  # ── 9b-d. --stamp-env: set, unset, and an unset value that is RECORDED ──
  # bd-8dn.  GATE_STAMP_ENVS is applied to EVERY gate (PKG, REPORT, EVAL,
  # DYNAMIC_SPACE_SIZE and whatever a project adds), so the unset case is the
  # common one and it has to behave like a value, not like an absence: if an
  # unset name were dropped from the manifest, the stamp would be a silent
  # no-op for every gate that does not set it and 9d's line is what says so.
  # MEASURED, the two digests below differ only in this variable.
  d1=$(unset BEAD8DN_VAR; digest_gate green "${opts[@]}" --stamp-env BEAD8DN_VAR 2>/dev/null)
  d2=$(BEAD8DN_VAR=a digest_gate green "${opts[@]}" --stamp-env BEAD8DN_VAR 2>/dev/null)
  check "9b --stamp-env: a set value changes the digest"          \
        "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"
  d2=$(unset BEAD8DN_VAR; digest_gate green "${opts[@]}" --stamp-env BEAD8DN_VAR 2>/dev/null)
  check "9c --stamp-env: an UNSET value is stable (deterministic)"  \
        "$(is "$([ "$d1" = "$d2" ] && echo 0 || echo 1)")"
  man=$(unset BEAD8DN_VAR; digest_gate green "${opts[@]}" --stamp-env BEAD8DN_VAR --verbose 2>/dev/null)
  check "9d --stamp-env: an UNSET value is RECORDED empty, not dropped" \
        "$(is "$(printf '%s\n' "$man" | grep -qE '^stamp BEAD8DN_VAR=$' && echo 0 || echo 1)")"

  # ── 10. a slash exclude is a PATH, not a basename ─────────────────────
  mkdir -p "$ROOT/build/keep" "$ROOT/sub/build"
  printf 'keep-me\n' >"$ROOT/build/keep/k.txt"
  printf 'not-me\n' >"$ROOT/sub/build/k.txt"
  local xin=( "${opts[@]}" --input build --input sub )
  d1=$(digest_gate excl "${xin[@]}" 2>/dev/null)
  d2=$(digest_gate excl "${xin[@]}" --exclude build 2>/dev/null)
  check "10a a bare glob 'build' prunes every build dir"         \
        "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"
  d1=$(digest_gate excl "${xin[@]}" --exclude build/keep 2>/dev/null)
  printf 'changed\n' >"$ROOT/build/keep/k.txt"
  d2=$(digest_gate excl "${xin[@]}" --exclude build/keep 2>/dev/null)
  check "10b the path exclude 'build/keep' hides that dir"        \
        "$(is "$([ "$d1" = "$d2" ] && echo 0 || echo 1)")"
  printf 'changed\n' >"$ROOT/sub/build/k.txt"
  d2=$(digest_gate excl "${xin[@]}" --exclude build/keep 2>/dev/null)
  check "10c the path exclude does not hide sub/build"            \
        "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"
  rm -rf "$ROOT/build" "$ROOT/sub"

  # ── 11. a cache that cannot be written must not break the gate ────────
  : >"$SCRATCH/notadir"
  : >"$COUNT"
  try_gate readonly "${opts[@]}" --cache "$SCRATCH/notadir" \
    -- "$FAKE" "$COUNT" "$LOG" 0 >/dev/null 2>&1
  rc=$?
  check "11 an unwritable cache still runs the gate and exits 0"  \
        "$(is "$([ "$(wc -l <"$COUNT")" -eq 1 ] && [ "$rc" -eq 0 ] && echo 0 || echo 1)")"

  # ── 12. a green exit with NO conclusion line is not a pass (bd-829) ─────
  # Measured instance: a test file failed to READ, SBCL aborted before
  # test-verdict.sh ran, the captured log ended in a backtrace, the recipe still
  # exited 0, and this tool recorded the build as GREEN.  The backtrace ECHOES
  # the guard's own --eval source, so the log really does contain the phrase
  # "test: NO TEST SYSTEM" — mid-line, inside frame 36.  That is why the pattern
  # is anchored, and that is what this check pins.
  local BROKEN=$SCRATCH/broken.sh
  cat >"$BROKEN" <<'EOS'
#!/usr/bin/env bash
# $1 = counter file, $2 = log.  Exits 0 having judged nothing.
echo run >>"$1"
{ printf 'caught 2 fatal ERROR conditions\n'
  printf '36: (SB-IMPL::PROCESS-EVAL/LOAD-OPTIONS ((:EVAL . #<(SIMPLE-ARRAY CHARACTER (292)) (unless (asdf:find-system "broken/tests" nil) (format t "~&test: NO TEST SYSTEM in this repo\n'
  printf 'unhandled condition in --disable-debugger mode, quitting\n'
} >"$2"
exit 0
EOS
  chmod +x "$BROKEN"
  local REQ='^(=== VERDICT: PASS|test: NO TEST SYSTEM( |$))'
  : >"$COUNT"; rm -rf "$CACHE/req"
  out=$(try_gate req "${opts[@]}" --require-log-match "$REQ" \
          -- "$BROKEN" "$COUNT" "$LOG" 2>&1); rc=$?
  check "12a a green exit whose log holds no conclusion line FAILS" \
        "$(is "$([ "$rc" -ne 0 ] && echo 0 || echo 1)")"
  check "12b ...and is not receipted"                         \
        "$(is "$([ ! -d "$CACHE/req" ] && echo 0 || echo 1)")"
  check "12c ...and it names the log to read"                  \
        "$(is "$(printf '%s' "$out" | grep -q "log to read is $LOG" && echo 0 || echo 1)")"
  check "12d a backtrace ECHO of the marker text does not satisfy it" \
        "$(is "$([ -z "$(grep -E "$REQ" "$LOG")" ] && echo 0 || echo 1)")"

  # The other half: the same shape is receipted when the declared line IS there.
  # Without this, a requirement that can never be satisfied would pass 12a-c.
  local CONCLUDED=$SCRATCH/concluded.sh
  cat >"$CONCLUDED" <<'EOS'
#!/usr/bin/env bash
# $1 = counter file, $2 = log.  Exits 0 having written a verdict line.
echo run >>"$1"
{ printf 'caught 0 fatal ERROR conditions\n'
  printf '=== VERDICT: PASS (target: req, log: %s) ===\n' "$2"
} >"$2"
exit 0
EOS
  chmod +x "$CONCLUDED"
  : >"$COUNT"; rm -rf "$CACHE/req"
  try_gate req "${opts[@]}" --require-log-match "$REQ" \
    -- "$CONCLUDED" "$COUNT" "$LOG" >/dev/null 2>&1; rc=$?
  check "12e a conclusion line at column 0 IS receipted"        \
        "$(is "$([ "$rc" -eq 0 ] && [ -d "$CACHE/req" ] && echo 0 || echo 1)")"

  # A verdict line that says FAIL must not be enough: a recipe that later exits 0
  # by some path would otherwise be receipted from a log that says the gate
  # failed.  Only the word PASS, at column 0, plus the no-test-system report.
  local FAILVERDICT=$SCRATCH/failverdict.sh
  cat >"$FAILVERDICT" <<'EOS'
#!/usr/bin/env bash
# $1 = counter file, $2 = log.  Exits 0 with a verdict line that says FAIL.
echo run >>"$1"
printf 'caught 1 ERROR condition\n=== VERDICT: FAIL (target: req, log: %s) ===\n' "$2" >"$2"
exit 0
EOS
  chmod +x "$FAILVERDICT"
  : >"$COUNT"; rm -rf "$CACHE/reqfail"
  out=$(try_gate reqfail "${opts[@]}" --require-log-match "$REQ" \
          -- "$FAILVERDICT" "$COUNT" "$LOG" 2>&1); rc=$?
  check "12f a FAIL verdict with a 0 exit is not receipted either" \
        "$(is "$([ "$rc" -ne 0 ] && [ ! -d "$CACHE/reqfail" ] && echo 0 || echo 1)")"

  # A receipt made while the requirement was LACKING must not answer for a gate
  # that now declares one: the requirement is part of the gate's definition, so
  # it is part of the digest.
  d1=$(digest_gate req "${opts[@]}" 2>/dev/null)
  d2=$(digest_gate req "${opts[@]}" --require-log-match "$REQ" 2>/dev/null)
  check "12g the requirement is part of the digest"             \
        "$(is "$([ "$d1" != "$d2" ] && echo 0 || echo 1)")"
  rm -f "$LOG"
  out=$(try_gate req "${opts[@]}" --require-log-match "$REQ" \
          -- "$CONCLUDED" "$COUNT" "$LOG" 2>&1); rc=$?
  check "12h a hit restores the judged log with its verdict line" \
        "$(is "$([ "$rc" -eq 0 ] && grep -q '^=== VERDICT: PASS' "$LOG" && echo 0 || echo 1)")"

  echo ""
  if [ "$SELF_FAILED" -eq 0 ]; then
    echo "== gate-receipt selftest: $SELF_CHECKS checks, 0 failed =="
    return 0
  fi
  echo "== gate-receipt selftest: $SELF_CHECKS checks, $SELF_FAILED FAILED =="
  return 1
}

# ── main ──────────────────────────────────────────────────────────────────
[ $# -gt 0 ] || { usage; exit 2; }
sub=$1; shift
case "$sub" in
  help|--help|-h) usage ;;
  run)      run_gate "$@" ;;
  digest)   digest_gate "$@" ;;
  why)      why_gate "$@" ;;
  selftest) selftest ;;
  status)
    CACHE_ARG=$PWD/.gate-cache
    while [ $# -gt 0 ]; do
      case "$1" in
        --cache)      CACHE_ARG=${2:-}; [ -n "$CACHE_ARG" ] || die "--cache needs a value"; shift 2 ;;
        --verbose|-v) VERBOSE=1; shift ;;
        *) die "unknown option $1" ;;
      esac
    done
    status_cache "$CACHE_ARG" ;;
  clean)
    CACHE_ARG=$PWD/.gate-cache
    GATES=()
    while [ $# -gt 0 ]; do
      case "$1" in
        --cache) CACHE_ARG=${2:-}; [ -n "$CACHE_ARG" ] || die "--cache needs a value"; shift 2 ;;
        --all)   GATES+=(--all); shift ;;
        *)       GATES+=("$1"); shift ;;
      esac
    done
    clean_cache "$CACHE_ARG" "${GATES[@]+"${GATES[@]}"}" ;;
  *) usage; exit 2 ;;
esac
